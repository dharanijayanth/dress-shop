export function getWhatsAppUrl(dressName = '', size = '', price = '') {
  let text = `Hello Zinzu Atelier! 👋 I am interested in purchasing a dress from your collection.`;
  if (dressName) {
    text = `Hello Zinzu Atelier! 👋 I would like to order:
👗 *Dress:* ${dressName}
${size ? `📐 *Size:* ${size}` : ''}
${price ? `🏷️ *Price:* ₹${price}` : ''}

Please confirm stock availability & payment details!`;
  }
  return `https://wa.me/${SHOP_WHATSAPP_NUMBER}?text=${encodeURIComponent(text)}`;
}

export function getCartCheckoutWhatsAppUrl(cartItems) {
  if (!cartItems || cartItems.length === 0) return getWhatsAppUrl();

  let text = `Hello Zinzu Atelier! 👋 I would like to place an order for the following items in my shopping bag:\n\n`;
  let total = 0;

  cartItems.forEach((item, index) => {
    const itemTotal = item.price * item.qty;
    total += itemTotal;
    text += `${index + 1}. *${item.name}*\n   Size: ${item.size} | Qty: ${item.qty} | Price: ₹${itemTotal}\n\n`;
  });

  text += `💰 *Grand Total:* ₹${total}\n🚚 *Shipping:* FREE Express Delivery\n\nPlease let me know how to proceed with payment!`;
  return `https://wa.me/${SHOP_WHATSAPP_NUMBER}?text=${encodeURIComponent(text)}`;
}
